def tl_point(t):
    """与 review_skel.py 同一套公式（T30 的 30 拍采样点）。"""
    T30 = T['T30']; i = T30['t'].index(t); land = T['map']['land']; our = T['ourTeam']; nT = T['humanTeams']
    sh = lambda x: round(100.0 * x / land, 1)
    order = sorted(range(1, nT + 1), key=lambda x: -T30['land'][i][x])
    return {'t': t, 'teamShare': {f'T{x}': sh(T30['land'][i][x]) for x in range(1, nT + 1)}, 'ourTeamRank': order.index(our) + 1,
            'botsShare': sh(T30['land'][i][0]), 'squadShare': sh(T30['squadLand'][i]), 'squadBal': T30['squadBal'][i],
            'squadDens': round(T30['squadBal'][i] / max(1, T30['squadLand'][i]), 1), 'squadActive': T30['squadActive'][i],
            'squadAlive': T30['squadAlive'][i], 'ourTeamActiveHumans': T30['active'][i][our], 'note': notes[t]}


